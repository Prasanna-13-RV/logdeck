import { test, expect, _electron as electron } from '@playwright/test'
import { mkdtemp, writeFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { expectFilterResults } from './viewerAssertions'

test('multiline receipts, counted find, Enter filters, reversible headers and both split orientations', async () => {
  const directory = await mkdtemp(join(tmpdir(), 'logdeck-viewer-workflow-'))
  const env = Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => typeof entry[1] === 'string'))
  env.LOGDECK_TEST_USER_DATA = join(directory, 'profile')
  delete env.ELECTRON_RUN_AS_NODE
  const desktop = await electron.launch({ args: [resolve('.')], env })
  try {
    const page = await desktop.firstWindow()
    await page.waitForFunction(() => Boolean(window.logdeck))
    const receipt = 'Formatted Receipt:\n\nSYNTHETIC VISA\nAMOUNT :             EUR 80.00\n\n    CANCELLATION APPROVED\n\nneedle NEEDLE\n\nMERCHANT RECEIPT\n'
    const messages = Array.from({ length: 1701 }, (_, index) => ({
      header: { logLevel: 'DEBUG', pid: index === 1700 ? 2 : 1, tid: 3,
        applicationId: 'example.synthetic', processName: 'example.synthetic', tag: index === 0 || index === 1700 ? 'Receipt' : 'Noise',
        timestamp: { seconds: 1788363267, nanos: 398000000 } },
      message: index === 0 ? receipt : index === 1700 ? 'distant needle' : index === 500 ? 'hit '.repeat(405) : `unrelated record ${index}`
    }))
    const path = join(directory, 'synthetic-receipts.logcat')
    await writeFile(path, JSON.stringify({ logcatMessages: messages }))
    const opened = await page.evaluate(path => window.logdeck.openDroppedFile(path), path)
    if (!opened.ok) throw new Error(opened.error)
    const panel = page.locator('.tab-panel:not([hidden])')
    await expect(panel.getByRole('button', { name: 'Apply filters', exact: true })).toBeEnabled()
    const firstRow = panel.locator('tbody tr').first()
    await expect(firstRow.locator('.message-cell')).toHaveText(receipt)
    expect(await firstRow.evaluate(node => node.getBoundingClientRect().height)).toBeGreaterThan(150)
    expect(await firstRow.locator('.message-cell').evaluate(node => getComputedStyle(node).whiteSpace)).toBe('pre')
    await expect.poll(async () => firstRow.evaluate(node => {
      const next = node.nextElementSibling
      return next ? next.getBoundingClientRect().top >= node.getBoundingClientRect().bottom - 1 : false
    })).toBe(true)
    await expect(panel.locator('.file-sidebar')).toHaveCount(0)
    await firstRow.locator('.line-cell').click()

    await page.keyboard.press('Control+f')
    const find = panel.getByRole('search')
    const input = find.getByLabel('Search logs', { exact: true })
    await expect(input).toBeFocused()
    await input.fill('needle')
    await expect(find.getByRole('status')).toHaveText('1 of 3 matches')
    await input.press('Enter')
    await expect(find.getByRole('status')).toHaveText('2 of 3 matches')
    await expect(panel.locator('mark.current-find')).toHaveText('NEEDLE')
    await input.press('Shift+Enter')
    await expect(find.getByRole('status')).toHaveText('1 of 3 matches')
    await input.press('Shift+Enter')
    await expect(find.getByRole('status')).toHaveText('3 of 3 matches')
    await expect(panel.locator('tr.find-row .line-cell')).toHaveText('1701')
    await expect(panel.locator('mark.current-find')).toBeInViewport()
    await input.press('Enter')
    await expect(find.getByRole('status')).toHaveText('1 of 3 matches')
    await expect(panel.locator('tr.selected .line-cell')).toHaveText('1')
    await panel.getByRole('button', { name: 'Wrap all columns', exact: true }).click()
    await input.press('Shift+Enter')
    await expect(find.getByRole('status')).toHaveText('3 of 3 matches')
    await expect(panel.locator('tr.find-row .line-cell')).toHaveText('1701')
    await input.press('Enter')
    await expect(find.getByRole('status')).toHaveText('1 of 3 matches')
    await panel.getByRole('button', { name: 'Wrap all columns', exact: true }).click()
    await find.getByLabel('Search case sensitive').check()
    await expect(find.getByRole('status')).toHaveText('1 of 2 matches')
    await find.getByLabel('Search case sensitive').uncheck()
    await input.fill('absent-value')
    await expect(find.getByRole('status')).toHaveText('0 of 0 matches')
    await expect(panel.getByRole('table')).toHaveAttribute('aria-rowcount', '1702')
    await input.fill('needle')
    await expect(find.getByRole('status')).toHaveText('1 of 3 matches')
    await input.fill('hit')
    await expect(find.getByRole('status')).toHaveText('1 of 405 matches')
    await input.press('Shift+Enter')
    await expect(find.getByRole('status')).toHaveText('405 of 405 matches')
    await expect(panel.locator('tr.find-row .line-cell')).toHaveText('501')
    await expect(panel.locator('mark.current-find')).toHaveText('hit')
    await expect(panel.locator('mark.current-find')).toBeInViewport()
    await input.fill('needle')
    await expect(find.getByRole('status')).toHaveText('1 of 3 matches')
    await input.press('Escape')
    await expect(find).toBeHidden()

    await expect(panel.getByLabel('Filter mode')).toHaveCount(0)
    await panel.getByLabel('Regex filter').fill('Receipt')
    await panel.getByLabel('Regex filter').press('Enter')
    await expectFilterResults(page, opened.value.id, 2)
    await panel.getByRole('button', { name: 'More filters', exact: true }).click()
    await panel.getByLabel('Filter pid', { exact: true }).fill('1')
    await panel.getByLabel('Filter pid', { exact: true }).press('Enter')
    await expectFilterResults(page, opened.value.id, 1)
    await panel.getByRole('button', { name: 'More filters', exact: true }).click()
    await page.keyboard.press('Control+f')
    await expect(find.getByRole('status')).toHaveText('1 of 2 matches')
    await find.getByRole('button', { name: 'Close find', exact: true }).click()
    await panel.getByLabel('Regex filter').fill('Receipt')
    await panel.getByLabel('Regex filter').press('Enter')
    await expectFilterResults(page, opened.value.id, 1)

    await page.getByRole('button', { name: 'Hide tab bar', exact: true }).click()
    await expect(page.locator('.navbar')).toBeHidden()
    await expect(page.getByRole('tablist')).toBeHidden()
    await panel.getByRole('button', { name: 'Hide filters and toolbar', exact: true }).click()
    await expect(panel.locator('.viewer-toolbar')).toBeHidden()
    await page.keyboard.press('Control+f')
    await expect(find).toBeVisible()
    await input.press('Escape')
    await panel.getByRole('button', { name: 'Show filters and toolbar', exact: true }).click()
    await page.getByRole('button', { name: 'Show navigation and tabs', exact: true }).click()
    await expect(page.locator('.navbar')).toBeVisible()
    await expect(page.getByRole('tablist')).toBeVisible()
    const normalHeight = await panel.getByLabel('Scrollable log table', { exact: true }).evaluate(node => node.clientHeight)
    await page.keyboard.press('F11')
    await expect(page.locator('.navbar')).toBeHidden()
    await expect(panel.locator('.viewer-toolbar')).toBeHidden()
    expect(await panel.getByLabel('Scrollable log table', { exact: true }).evaluate(node => node.clientHeight)).toBeGreaterThan(normalHeight)
    await page.getByRole('button', { name: 'Show navigation and tabs', exact: true }).click()

    await panel.getByRole('button', { name: 'Split view', exact: true }).click()
    const panes = panel.locator('.split-pane')
    await expect(panes).toHaveCount(2)
    const top = await panes.nth(0).boundingBox()
    const bottom = await panes.nth(1).boundingBox()
    expect(bottom!.y).toBeGreaterThan(top!.y)
    await panel.getByRole('button', { name: 'Split side by side', exact: true }).click()
    const left = await panes.nth(0).boundingBox()
    const right = await panes.nth(1).boundingBox()
    expect(right!.x).toBeGreaterThan(left!.x)
    expect(right!.y).toBe(left!.y)
    await expect(panes.nth(0).getByLabel('Regex filter')).toHaveValue('Receipt')
    await expect(panes.nth(1).getByLabel('Regex filter')).toHaveValue('')
    await panes.nth(1).getByLabel('Regex filter').click()
    await page.keyboard.press('Control+f')
    await expect(panes.nth(0).getByRole('search')).toHaveCount(0)
    await panes.nth(1).getByLabel('Search logs', { exact: true }).fill('needle')
    await expect(panes.nth(1).getByRole('search').getByRole('status')).toHaveText('1 of 3 matches')
    await page.keyboard.press('Escape')
    await panel.getByRole('button', { name: 'Stack split views', exact: true }).click()
    await panel.getByRole('button', { name: 'Close split', exact: true }).click()
    await expect(panes).toHaveCount(1)

    const findAll = await page.evaluate(id => window.logdeck.startFind({ id, query: 'needle', columns: ['message'], caseSensitive: false }), opened.value.id)
    if (!findAll.ok) throw new Error(findAll.error)
    await expect.poll(async () => {
      const result = await page.evaluate(id => window.logdeck.findStatus(id), opened.value.id)
      return result.ok && result.value.status
    }).toBe('ready')
    const lastMatch = await page.evaluate(request => window.logdeck.findMatch(request), { id: opened.value.id, version: findAll.value.version, ordinal: 3 })
    expect(lastMatch.ok && lastMatch.value.position).toBe(1701)
    const replacement = await page.evaluate(id => window.logdeck.startFind({ id, query: 'hit', columns: ['message'], caseSensitive: false }), opened.value.id)
    if (!replacement.ok) throw new Error(replacement.error)
    const stale = await page.evaluate(request => window.logdeck.findMatch(request), { id: opened.value.id, version: findAll.value.version, ordinal: 1 })
    expect(stale.ok).toBe(false)
    const cancelled = await page.evaluate(id => window.logdeck.cancelFind(id), opened.value.id)
    expect(cancelled.ok).toBe(true)
    const released = await page.evaluate(id => window.logdeck.findStatus(id), opened.value.id)
    expect(released.ok).toBe(false)
    const filter = await page.evaluate(id => window.logdeck.searchStatus(id), opened.value.id)
    expect(filter.ok && filter.value.matches).toBe(1)

    const oversizedPath = join(directory, 'oversized-find.log')
    await writeFile(oversizedPath, 'Z'.repeat(1_000_001))
    const oversized = await page.evaluate(path => window.logdeck.openDroppedFile(path), oversizedPath)
    if (!oversized.ok) throw new Error(oversized.error)
    await expect(panel.getByRole('button', { name: 'Apply filters', exact: true })).toBeEnabled()
    const oversizedFind = await page.evaluate(id => window.logdeck.startFind({ id, query: 'Z', columns: ['message'], caseSensitive: true }), oversized.value.id)
    expect(oversizedFind.ok).toBe(true)
    await expect.poll(async () => {
      const result = await page.evaluate(id => window.logdeck.findStatus(id), oversized.value.id)
      return result.ok && result.value.status === 'error' && result.value.error
    }).toContain('1 MB search-record limit')
    expect(await page.getByRole('alert').allTextContents()).toEqual([])
  } finally {
    await desktop.close()
    await rm(directory, { recursive: true, force: true })
  }
})

test('independent split files, keyboard selection, settings columns and legacy preset warning', async () => {
  const directory = await mkdtemp(join(tmpdir(), 'logdeck-split-file-'))
  const env = Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => typeof entry[1] === 'string'))
  env.LOGDECK_TEST_USER_DATA = join(directory, 'profile')
  delete env.ELECTRON_RUN_AS_NODE
  const desktop = await electron.launch({ args: [resolve('.')], env })
  try {
    const page = await desktop.firstWindow()
    await page.waitForFunction(() => Boolean(window.logdeck))
    const primaryPath = join(directory, 'primary.log')
    const otherPath = join(directory, 'other.logcat')
    await writeFile(primaryPath, Array.from({ length: 405 }, (_, i) => `10-24 12:00:00.000 1 2 D Primary: record ${i + 1}`).join('\n'))
    await writeFile(otherPath, JSON.stringify({ logcatMessages: [{
      header: { logLevel: 'INFO', pid: 9, tid: 8, tag: 'Secondary', timestamp: { seconds: 0, nanos: 0 } },
      message: 'Other file\nTag 9F33: E0F8C8'
    }] }))
    const opened = await page.evaluate(path => window.logdeck.openDroppedFile(path), primaryPath)
    if (!opened.ok) throw new Error(opened.error)
    const panel = page.locator('.tab-panel:not([hidden])')
    await expect(panel.getByRole('button', { name: 'Apply filters', exact: true })).toBeEnabled()
    await expect(panel.getByRole('button', { name: 'Columns', exact: true })).toHaveCount(0)
    await expect(panel.getByLabel('Filter mode')).toHaveCount(0)
    await panel.locator('tbody tr[data-index="0"] .line-cell').click()
    await page.keyboard.press('ArrowUp')
    await expect(panel.locator('tr.selected .line-cell')).toHaveText('1')
    await page.keyboard.press('ArrowDown')
    await expect(panel.locator('tr.selected .line-cell')).toHaveText('2')
    await page.keyboard.press('ArrowUp')
    await expect(panel.locator('tr.selected .line-cell')).toHaveText('1')
    await panel.getByRole('button', { name: 'Wrap all columns', exact: true }).click()
    await panel.getByLabel('Source line number', { exact: true }).fill('200')
    await panel.getByRole('button', { name: 'Go to source line', exact: true }).click()
    await panel.getByLabel('Scrollable log table', { exact: true }).focus()
    await page.keyboard.press('ArrowDown')
    await expect(panel.locator('tr.selected .line-cell')).toHaveText('201')
    await page.keyboard.press('ArrowUp')
    await expect(panel.locator('tr.selected .line-cell')).toHaveText('200')
    await panel.getByLabel('Regex filter').fill('record (?:1|3)$')
    await panel.getByLabel('Regex filter').press('Enter')
    await expectFilterResults(page, opened.value.id, 2)
    await panel.locator('tbody tr[data-index="0"] .line-cell').click()
    await page.keyboard.press('ArrowDown')
    await expect(panel.locator('tr.selected .line-cell')).toHaveText('3')
    await page.keyboard.press('ArrowDown')
    await expect(panel.locator('tr.selected .line-cell')).toHaveText('3')
    await panel.getByLabel('Regex filter').focus()
    await page.keyboard.press('ArrowUp')
    await expect(panel.locator('tr.selected .line-cell')).toHaveText('3')

    await desktop.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }) }, otherPath)
    await panel.getByRole('button', { name: 'Open another log in split', exact: true }).click()
    const panes = panel.locator('.split-pane')
    await expect(panes).toHaveCount(2)
    await expect(panes.nth(1).locator('tbody')).toContainText('Other file')
    await expectFilterResults(page, opened.value.id, 2)
    await expect(page.getByRole('tab', { name: 'primary.log', exact: true })).toBeVisible()
    await expect(page.getByRole('tab', { name: 'other.logcat', exact: true })).toHaveCount(0)
    await panel.getByRole('button', { name: 'Split side by side', exact: true }).click()
    await expect(panes.nth(1).getByRole('button', { name: 'Inspect EMV tag 9F33', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Appearance and settings', exact: true }).click()
    await page.getByRole('dialog').getByLabel('Show pid column', { exact: true }).uncheck()
    await page.keyboard.press('Escape')
    await expect(panel.getByRole('columnheader', { name: 'PID', exact: true })).toHaveCount(0)
    for (const theme of ['Light', 'Dark']) {
      await page.getByRole('button', { name: 'Appearance and settings', exact: true }).click()
      await page.getByRole('button', { name: theme, exact: true }).click()
      await page.keyboard.press('Escape')
      const tag = panes.nth(1).getByRole('button', { name: 'Inspect EMV tag 9F33', exact: true })
      expect(await tag.evaluate(node => {
        const style = getComputedStyle(node)
        return { weight: style.fontWeight, bordered: parseFloat(style.borderTopWidth) > 0, filled: style.backgroundColor !== 'rgba(0, 0, 0, 0)' }
      })).toEqual({ weight: '700', bordered: true, filled: true })
    }
    const sessions = await page.evaluate(() => window.logdeck.getSessions())
    if (!sessions.ok) throw new Error(sessions.error)
    const secondaryId = sessions.value.find(info => info.splitParentId === opened.value.id)!.id
    await desktop.evaluate(({ dialog }) => { dialog.showOpenDialog = async () => ({ canceled: true, filePaths: [] }) })
    await panes.nth(1).getByRole('button', { name: 'Open another log', exact: true }).click()
    await expect(panes.nth(1).locator('tbody')).toContainText('Other file')
    await desktop.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }) }, join(directory, 'missing.logcat'))
    await panes.nth(1).getByRole('button', { name: 'Open another log', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('ENOENT')
    await page.getByRole('button', { name: 'Dismiss error', exact: true }).click()
    await expect(panes.nth(1).locator('tbody')).toContainText('Other file')
    await page.reload()
    await expect(panes).toHaveCount(2)
    await expect(panes.nth(1).locator('tbody')).toContainText('Other file')
    await expect(page.getByRole('tab', { name: 'other.logcat', exact: true })).toHaveCount(0)
    await desktop.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }) }, primaryPath)
    await panes.nth(1).getByRole('button', { name: 'Open another log', exact: true }).click()
    await expect(panes.nth(1).locator('tbody')).toContainText('record 1')
    expect((await page.evaluate(id => window.logdeck.readRange({ id, start: 1, count: 1 }), secondaryId)).ok).toBe(false)
    await page.evaluate(() => {
      localStorage.setItem('logdeck-presets', JSON.stringify([{ id: 'legacy', name: 'Old expression', query: 'tag:Primary', filters: {}, caseSensitive: false, mode: 'expression' }]))
      window.dispatchEvent(new Event('logdeck-presets'))
    })
    await panes.nth(0).getByRole('button', { name: 'More filters', exact: true }).click()
    await panes.nth(0).getByLabel('Saved preset').selectOption('legacy')
    await expect(page.getByRole('alert')).toContainText('retired expression syntax')
    await expect(panes.nth(0).getByLabel('Regex filter')).toHaveValue('')
    expect(await page.evaluate(() => JSON.parse(localStorage.getItem('logdeck-presets')!)[0].query)).toBe('tag:Primary')
    await page.getByRole('button', { name: 'Dismiss error', exact: true }).click()
    await page.getByRole('button', { name: 'Close file', exact: true }).click()
    const remaining = await page.evaluate(() => window.logdeck.getSessions())
    expect(remaining.ok && remaining.value.length).toBe(0)
  } finally {
    await desktop.close()
    await rm(directory, { recursive: true, force: true })
  }
})
