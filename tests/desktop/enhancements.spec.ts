import { test, expect, _electron as electron } from '@playwright/test'
import { mkdtemp, writeFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { expectFilterResults } from './viewerAssertions'

async function launch() {
  const directory = await mkdtemp(join(tmpdir(), 'logdeck-enhancements-'))
  const env = Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => typeof entry[1] === 'string'))
  env.LOGDECK_TEST_USER_DATA = join(directory, 'profile')
  delete env.ELECTRON_RUN_AS_NODE
  const desktop = await electron.launch({ args: [resolve('.')], env })
  const page = await desktop.firstWindow()
  await page.waitForFunction(() => Boolean(window.logdeck))
  return { directory, desktop, page }
}

test('whole-table scroll, synchronized slider, measured wrap, tabs and disk-backed search', async () => {
  const { directory, desktop, page } = await launch()
  try {
    const path = join(directory, 'first-synthetic.log')
    const secondPath = join(directory, 'second-synthetic.log')
    await writeFile(path, Array.from({ length: 2000 }, (_, i) =>
      `10-24 12:00:00.000 123 456 ${i % 2 ? 'D' : 'W'} ${i % 2 ? 'Network' : 'Payment'}: ${'long message '.repeat(35)} item ${i + 1}`
    ).join('\n'))
    await writeFile(secondPath, '10-24 12:00:00.000 999 888 I Other: second file\n')
    const opened = await page.evaluate(path => window.logdeck.openDroppedFile(path), path)
    if (!opened.ok) throw new Error(opened.error)
    await expect(page.getByRole('table', { name: 'Log lines' })).toBeVisible()
    await expect.poll(async () => {
      const result = await page.evaluate(() => window.logdeck.getSession())
      return result.ok && result.value?.status
    }).toBe('ready')
    await expect(page.locator('.tab-panel:not([hidden]) tbody tr').first()).toContainText('item 1')
    await expect(page).toHaveTitle('first-synthetic.log - LogDeck')
    expect(await desktop.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].getTitle())).toBe('first-synthetic.log - LogDeck')
    await page.locator('.tab-panel:not([hidden]) tbody tr').first().click()
    await expect(page.getByText('MESSAGE DETAILS', { exact: true })).toHaveCount(0)
    const scroll = page.getByLabel('Scrollable log table', { exact: true })
    expect(await scroll.evaluate(node => node.scrollWidth > node.clientWidth)).toBe(true)
    await scroll.evaluate(node => { node.scrollLeft = 600; node.scrollTop = 2800 })
    await expect.poll(async () => Number(await page.getByLabel('Global source position').inputValue())).toBeGreaterThan(50)
    expect(await scroll.evaluate(node => node.scrollLeft)).toBeGreaterThan(0)
    const position = Number(await page.getByLabel('Global source position').inputValue())
    await page.getByRole('button', { name: 'Wrap all columns' }).click()
    await expect(page.getByRole('button', { name: 'Wrap all columns' })).toHaveAttribute('aria-pressed', 'true')
    await expect.poll(() => scroll.evaluate(node => node.scrollWidth <= node.clientWidth + 1)).toBe(true)
    await expect.poll(() => page.locator('.tab-panel:not([hidden]) tbody tr').first().evaluate(node => node.getBoundingClientRect().height)).toBeGreaterThan(28)
    expect(await page.locator('.tab-panel:not([hidden]) tbody tr').count()).toBeLessThan(80)
    await page.getByRole('button', { name: 'Wrap all columns' }).click()
    await page.getByLabel('Regex filter').fill(' W (?:Payment|Network):')
    await page.getByRole('button', { name: 'Apply filters', exact: true }).click()
    await expectFilterResults(page, opened.value.id, 1000)
    const status = await page.evaluate(id => window.logdeck.searchStatus(id), opened.value.id)
    if (!status.ok) throw new Error(status.error)
    const matches = await page.evaluate(request => window.logdeck.readRange(request), {
      id: opened.value.id, start: 1, count: 2, searchVersion: status.value.version
    })
    if (!matches.ok) throw new Error(matches.error)
    expect(matches.value.map(row => row.line)).toEqual([1, 3])
    await page.getByLabel('Source line number', { exact: true }).fill('2')
    await page.getByRole('button', { name: 'Go to source line' }).click()
    await expect(page.getByRole('alert')).toContainText('filtered out')
    await page.getByRole('button', { name: 'Dismiss error' }).click()
    await page.getByLabel('Regex filter').fill('[')
    await page.getByRole('button', { name: 'Apply filters', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('Invalid')
    await page.getByRole('button', { name: 'Reset filters', exact: true }).click()
    await page.getByRole('button', { name: 'More filters', exact: true }).click()
    await page.getByLabel('Filter pid').fill('999')
    await page.getByRole('button', { name: 'Apply filters' }).click()
    await expectFilterResults(page, opened.value.id, 0)
    await page.getByRole('button', { name: 'Reset filters', exact: true }).click()
    await page.getByRole('button', { name: 'More filters', exact: true }).click()
    await page.getByLabel('Source line number', { exact: true }).fill('125')
    await page.getByRole('button', { name: 'Go to source line' }).click()
    await expect.poll(async () => Number(await page.getByLabel('Global source position').inputValue())).toBeGreaterThan(100)
    await page.keyboard.press('Control+t')
    await expect(page.getByRole('button', { name: 'Browse files' })).toBeVisible()
    const second = await page.evaluate(path => window.logdeck.openDroppedFile(path), secondPath)
    if (!second.ok) throw new Error(second.error)
    await expect(page).toHaveTitle('second-synthetic.log - LogDeck')
    await expect(page.getByRole('tab', { name: 'first-synthetic.log' })).toBeVisible()
    await page.getByRole('tab', { name: 'first-synthetic.log' }).click()
    await expect(page).toHaveTitle('first-synthetic.log - LogDeck')
    const panel = page.locator('.tab-panel:not([hidden])')
    await expect(panel.getByLabel('Regex filter')).toHaveValue('')
    await expect.poll(async () => Number(await panel.getByLabel('Global source position').inputValue())).toBeGreaterThan(100)
    await expect(panel.locator('tbody')).toContainText('item 125')
    await page.screenshot({ path: 'test-results/tabs-viewer-synthetic.png' })
    await panel.getByLabel('Source line number', { exact: true }).fill(String(position))
    await page.getByRole('button', { name: 'Go to source line' }).click()
    await expect.poll(async () => Number(await panel.getByLabel('Global source position').inputValue())).toBeGreaterThan(20)
    await page.getByRole('tab', { name: 'second-synthetic.log' }).click()
    await page.keyboard.press('Control+w')
    await expect(page.getByRole('tab', { name: 'second-synthetic.log' })).toHaveCount(0)
    const remains = await page.evaluate(id => window.logdeck.readRange({ id, start: 1, count: 1 }), opened.value.id)
    expect(remains.ok).toBe(true)
    const nextWindow = desktop.waitForEvent('window')
    await page.getByRole('button', { name: 'New window', exact: true }).click()
    const other = await nextWindow
    await expect(other.getByRole('button', { name: 'Browse files' })).toBeVisible()
    const denied = await other.evaluate(id => window.logdeck.searchStatus(id), opened.value.id)
    expect(denied.ok).toBe(false)
    await other.close()
  } finally {
    await desktop.close()
    await rm(directory, { recursive: true, force: true })
  }
})

