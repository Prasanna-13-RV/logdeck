test('search cancellation, stale generations, same-file tab isolation and oversized record errors', async () => {
  const { directory, desktop, page } = await launch()
  try {
    const path = join(directory, 'search-cancel-synthetic.log')
    await writeFile(path, '10-24 12:00:00.000 123 456 I Test: synthetic searchable message\n'.repeat(100_000))
    const opened = await page.evaluate(path => window.logdeck.openDroppedFile(path), path)
    if (!opened.ok) throw new Error(opened.error)
    const id = opened.value.id
    await expect.poll(async () => {
      const result = await page.evaluate(() => window.logdeck.getSession())
      return result.ok && result.value?.status
    }, { timeout: 30000 }).toBe('ready')
    const search = await page.evaluate(id => window.logdeck.startSearch({ id, query: 'synthetic', filters: {}, caseSensitive: false }), id)
    if (!search.ok) throw new Error(search.error)
    const cancelled = await page.evaluate(id => window.logdeck.cancelSearch(id), id)
    expect(cancelled.ok).toBe(true)
    const state = await page.evaluate(id => window.logdeck.searchStatus(id), id)
    if (!state.ok) throw new Error(state.error)
    expect(state.value.status).toBe('cancelled')
    expect(state.value.scanned).toBeLessThan(100_000)
    const next = await page.evaluate(id => window.logdeck.startSearch({ id, query: 'level:E', filters: {}, caseSensitive: false }), id)
    if (!next.ok) throw new Error(next.error)
    const outdated = await page.evaluate(request => window.logdeck.readRange(request), { id, start: 1, count: 1, searchVersion: search.value.version })
    expect(outdated.ok).toBe(false)
    await page.evaluate(id => window.logdeck.cancelSearch(id), id)
    const second = await page.evaluate(path => window.logdeck.openDroppedFile(path), path)
    if (!second.ok) throw new Error(second.error)
    const separate = await page.evaluate(id => window.logdeck.searchStatus(id), second.value.id)
    expect(separate.ok).toBe(false)
    const oldSearch = await page.evaluate(id => window.logdeck.searchStatus(id), id)
    expect(oldSearch.ok && oldSearch.value.version).toBe(next.value.version)
    await page.evaluate(id => window.logdeck.closeFile(id), second.value.id)
    const stillOpen = await page.evaluate(id => window.logdeck.readRange({ id, start: 1, count: 1 }), id)
    expect(stillOpen.ok).toBe(true)
    const oversizedPath = join(directory, 'oversized-search-record.log')
    await writeFile(oversizedPath, 'x'.repeat(1_000_001))
    const oversized = await page.evaluate(path => window.logdeck.openDroppedFile(path), oversizedPath)
    if (!oversized.ok) throw new Error(oversized.error)
    await expect.poll(async () => {
      const result = await page.evaluate(() => window.logdeck.getSession())
      return result.ok && result.value?.status
    }).toBe('ready')
    await page.evaluate(id => window.logdeck.startSearch({ id, query: 'x', filters: {}, caseSensitive: false }), oversized.value.id)
    await expect.poll(async () => {
      const result = await page.evaluate(id => window.logdeck.searchStatus(id), oversized.value.id)
      return result.ok && result.value.status
    }).toBe('error')
    const failure = await page.evaluate(id => window.logdeck.searchStatus(id), oversized.value.id)
    expect(failure.ok && failure.value.error).toContain('1 MB search-record limit')
  } finally {
    await desktop.close()
    await rm(directory, { recursive: true, force: true })
  }
})
