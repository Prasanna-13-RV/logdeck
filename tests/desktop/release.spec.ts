import { test, expect, _electron as electron, type Locator, type ElectronApplication } from '@playwright/test'
import { mkdtemp, writeFile, readFile, rm, readdir } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import { tmpdir } from 'node:os'

async function launch() {
  const directory = await mkdtemp(join(tmpdir(), 'logdeck-release-'))
  const env = Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => typeof entry[1] === 'string'))
  env.LOGDECK_TEST_USER_DATA = join(directory, 'profile')
  delete env.ELECTRON_RUN_AS_NODE
  const desktop = await electron.launch({ args: [resolve('.')], env })
  await desktop.evaluate(({ dialog }) => { dialog.showMessageBoxSync = () => 1 })
  const page = await desktop.firstWindow()
  await page.waitForFunction(() => Boolean(window.logdeck))
  return { directory, desktop, page }
}

async function expectEditor(editor: Locator, text: string) {
  await expect.poll(async () => (await editor.locator('.cm-line').allTextContents()).join('\n')).toBe(text)
}

async function replaceEditor(desktop: ElectronApplication, editor: Locator, text: string, expected = text) {
  const previous = await desktop.evaluate(async ({ clipboard }, text) => {
    const previous = await clipboard.readText()
    await clipboard.writeText(text)
    return previous
  }, text)
  try {
    await editor.press('Control+a')
    await editor.press('Control+v')
    await expectEditor(editor, expected)
  } finally { await desktop.evaluate(({ clipboard }, text) => clipboard.writeText(text), previous) }
}

